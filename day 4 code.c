// Q7 Write a program to swap two numbers without using a third variable

 #include <stdio.h>
int main()
{
    int c, a;

    printf("enter two numbers = ");
    scanf("%d,%d", &c, &a);
    printf("after swap = %d,%d", a,c);

    return 0;
}


 


